/** URL-friendly kebab-case. NFD then strip combining marks keeps Unicode
 *  letters (é → e), so accented input slugifies without losing the accent. */
export function slugify(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_]+/g, '-')
    .replace(/-+/g, '-');
}
